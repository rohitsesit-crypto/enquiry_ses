// =============================================================================
// app/lib/enquiryId.ts   —  the Entry_ID, never "Not set" when the sheet has one
// =============================================================================
// The "Entries" tab holds these ids:
//
//     ENQ-00001   ENQP-00003   ENQPP-00008   ENQU-00125   ENQU-00048
//
// Three lookup steps, in order:
//   1. The id column, matched by header name (Entry_ID / Entry ID / Enquiry ID /
//      Entry ID (Auto) / Entry No / ENQ No / entry_id / EntryId ...).
//   2. If that cell is empty or missing, a value scan limited to the ENQ series
//      only — so a real id is recovered even when the header was renamed.
//   3. Nothing left → '' and the UI shows that the sheet cell is blank.
//
// Document numbers are never accepted by any step: "B-523/26-27" (challan),
// "P0000133" (party code), "P018263243" (document no.), PO / INV / GP / CH
// numbers. They are rejected by shape, not by a fixed list of three values.
// =============================================================================

/** Header keys this sheet has used for the id column, after normalisation. */
const ID_COLUMN_KEYS = ["entryid", "enquiryid", "enqid", "entryno", "enquiryno", "enqno"];

/**
 * Columns that hold free text. The fallback scan skips them so an enquiry id
 * mentioned inside a remark ("repeat of ENQ-00001") can never be picked up as
 * this row's own id.
 */
const TEXT_COLUMN_HINTS = [
  "remark", "remarks", "note", "notes", "description", "comment", "comments",
  "json", "history", "log", "reason", "address", "detail", "details",
];

/**
 * 'Entry_ID' / 'Entry ID' / 'EntryId' / 'Entry ID (Auto)' / 'Enquiry ID'
 * all collapse to 'entryid' or 'enquiryid'.
 *
 * Parentheticals and generator words are removed first, exactly like the
 * Apps Script side, so "Entry ID (Auto Generated)" is not a different column.
 */
export function entryIdKey(key: string): string {
  return String(key ?? "")
    .replace(/\(.*?\)/g, " ")
    .replace(/\b(auto|autogenerated|generated|system)\b/gi, " ")
    .replace(/[^a-z0-9]/gi, "")
    .toLowerCase();
}

function isIdColumn(key: string): boolean {
  const k = entryIdKey(key);
  if (ID_COLUMN_KEYS.includes(k)) return true;
  // "Entry_ID_Auto", "EnquiryId" and similar compound headers.
  return /^(entry|enquiry|enq)(id|no)$/.test(k) || k.endsWith("entryid");
}

/** True for free-text columns the fallback scan must not read as an id. */
function isTextColumn(key: string): boolean {
  const k = entryIdKey(key);
  return TEXT_COLUMN_HINTS.some((hint) => k.includes(hint));
}

/**
 * The enquiry series used by this sheet: ENQ, ENQP, ENQPP, ENQU, ...
 * A separator is optional and may be -, /, _ or a space; digits may be grouped.
 */
const ENQUIRY_SERIES = /^ENQ[\s/_-]?[\sA-Z0-9/_-]{1,24}$/i;

/** Generic id series: 2-6 letters, then one or more separator+digits groups. */
const GENERIC_SERIES = /^[A-Z]{2,6}(?:[\s/-]\d{1,10})+$/i;

/**
 * Prefixes that belong to other documents. They keep the generic branch from
 * accepting a purchase order, invoice or gate pass that was pasted by mistake.
 */
const NON_ID_PREFIXES = [
  "PO", "INV", "INVOICE", "BILL", "GP", "GATEPASS", "LR", "CH", "CHALLAN",
  "QN", "QNO", "SER", "SERIAL", "DOC", "GRN", "REF", "TMP", "TEMP",
];

/** True when the text belongs to the ENQ enquiry series (any case/separator). */
function isEnquirySeries(text: string): boolean {
  const t = text.trim();
  if (!t || t.length > 32) return false;
  if (!/\d/.test(t)) return false;
  return ENQUIRY_SERIES.test(t);
}

/**
 * True when the text is a real enquiry id and not a document/party number.
 *
 *   ENQ-00001  ENQP-00003  ENQPP-00008  ENQU-00125  ENQ00001  SES/26/0187  -> true
 *   B-523/26-27  P0000133  P018263243  21  2026-0187  PO-2026-0187          -> false
 */
export function isEntryIdShape(value: string): boolean {
  const text = String(value ?? "").trim();
  if (!text || text.length > 32) return false;
  if (!/\d/.test(text)) return false;

  if (ENQUIRY_SERIES.test(text)) return true;
  if (!GENERIC_SERIES.test(text)) return false;

  const prefix = text.split(/[\s/-]/)[0].toUpperCase();
  return !NON_ID_PREFIXES.includes(prefix);
}

/**
 * Reads one sheet cell as clean text.
 *
 * Cells pasted from Excel often carry zero-width spaces, non-breaking spaces or
 * soft hyphens. Those are invisible, so such a cell looks empty and the stored
 * id would be lost — they are stripped, nothing else is changed.
 */
function readCell(raw: unknown): string {
  if (raw === null || raw === undefined) return "";
  if (typeof raw === "object") return "";
  return String(raw)
    .replace(/[\u200B-\u200D\uFEFF\u00AD]/g, "")
    .replace(/\u00A0/g, " ")
    .trim();
}

/**
 * Diagnostics for one row: which value was found, the raw cell, and why the
 * lookup ended the way it did. Used by the UI to explain a blank id instead of
 * silently printing "Not set".
 */
export interface EnquiryIdInfo {
  /** Usable id, or '' when the row genuinely has none. */
  id: string;
  /** The id column's raw cell, even when it is not a usable id. */
  rawCell: string;
  /** How the id was found. */
  source: "column" | "row-scan" | "none";
  /** Header that was treated as the id column, when one was found. */
  column: string;
}

export function getEnquiryIdInfo(entry: Record<string, unknown> | null | undefined): EnquiryIdInfo {
  if (!entry) return { id: "", rawCell: "", source: "none", column: "" };

  let rawCell = "";
  let column = "";

  // 1. The id column, whatever the header was called.
  for (const key of Object.keys(entry)) {
    if (!isIdColumn(key)) continue;
    const raw = readCell(entry[key]);
    if (raw && !rawCell) {
      rawCell = raw;
      column = key;
    }
    if (raw && isEntryIdShape(raw)) {
      return { id: raw.toUpperCase(), rawCell: raw, source: "column", column: key };
    }
  }

  // 2. Fallback: find the id value itself. Restricted to the ENQ series and to
  //    short cells, so a challan number, party code, PO or a remark that merely
  //    mentions an id can never be recovered as this row's id.
  for (const key of Object.keys(entry)) {
    if (isTextColumn(key)) continue;
    const raw = readCell(entry[key]);
    if (!raw || raw.length > 32) continue;
    if (!isEnquirySeries(raw)) continue;
    if (!column) column = key;
    return { id: raw.toUpperCase(), rawCell: rawCell || raw, source: "row-scan", column };
  }

  return { id: "", rawCell, source: "none", column };
}

/**
 * The Entry_ID for one row, or '' when the row has none.
 *
 * Used for display and for the step payload. A row whose id cell holds a
 * challan/party/document number returns '' rather than the wrong value.
 */
export function getEnquiryId(entry: Record<string, unknown> | null | undefined): string {
  return getEnquiryIdInfo(entry).id;
}

/** True when the sheet's Entry_ID cell holds a usable enquiry id. */
export function hasEnquiryId(entry: Record<string, unknown>): boolean {
  return getEnquiryId(entry) !== "";
}

/**
 * Raw Entry_ID cell contents, even when it is not a valid id.
 *
 * Returns the first NON-EMPTY candidate, because a normalised row can carry
 * both the original header key and the canonical `Entry_ID` key.
 * Used for diagnostics and as the last-resort write key — never rendered as
 * the entry id on its own.
 */
export function getRawEntryIdCell(entry: Record<string, unknown> | null | undefined): string {
  if (!entry) return "";
  for (const key of Object.keys(entry)) {
    if (!isIdColumn(key)) continue;
    const raw = readCell(entry[key]);
    if (raw) return raw;
  }
  return "";
}

/**
 * The value used to locate a row when writing back to the sheet.
 *
 * A write must use whatever the Entry_ID cell actually holds, otherwise the
 * Apps Script lookup cannot find the row and the step submission fails. So this
 * prefers the real id, then falls back to the raw cell text (the sheet's own
 * key), and only returns '' when the cell is genuinely empty.
 *
 * Never render this value — that is what getEnquiryId() is for.
 */
export function getEntryWriteKey(entry: Record<string, unknown> | null | undefined): string {
  return getEnquiryId(entry) || getRawEntryIdCell(entry) || "";
}

/**
 * What the detail panel should print for "Entry ID".
 *
 * Returns the id when there is one. When the row has a cell but it is not a
 * usable id, the raw text is returned with `warning` set, so the value is never
 * hidden and a bad cell is visible instead of a silent "Not set".
 */
export function getEnquiryIdDisplay(
  entry: Record<string, unknown> | null | undefined
): { value: string; warning: boolean } {
  const info = getEnquiryIdInfo(entry);
  if (info.id) return { value: info.id, warning: false };
  if (info.rawCell) return { value: info.rawCell, warning: true };
  return { value: "", warning: false };
}

/**
 * INTERNAL React list key only — never rendered and never sent to the backend.
 */
export function getEntryRef(entry: Record<string, unknown>, rowIndex = 0): string {
  const id = getEnquiryId(entry);
  if (id) return id;

  const serial = readCell(entry?.Serial_No);
  if (serial && serial !== "0") return `SERIAL:${serial}`;

  return `ROW:${rowIndex}`;
}
