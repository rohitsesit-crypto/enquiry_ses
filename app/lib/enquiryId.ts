// =============================================================================
// app/lib/enquiryId.ts   —  ENTRY ID, READ FROM THE SHEET'S Entry_ID COLUMN
// =============================================================================
// One job only: read the row's Entry_ID cell and return that text.
//
//     ENQU-00048      ENQ-00001      ENQP-00003      ENQPP-00008
//
// Resolution order
//   1. the exact "Entry_ID" column
//   2. a header that differs only by spelling: "Entry ID", "EntryId", "Enq No"
//   3. with unknown headers, a value that is shaped like an id
//   4. nothing — '' is returned and the UI renders no id
//
// Never looked at: Serial_No, PO number, gate pass, challan, LR, invoice,
// mobile, GST, office, location, timestamp. Nothing is prefixed, padded or
// generated. An empty cell stays empty, so no "S.No 125" style label and no
// internal ROW:/SERIAL: reference can ever be shown as the enquiry id.
// =============================================================================

/** 'Entry_ID' / 'entry id' / 'EntryId' / 'Entry ID '  ->  'entryid' */
export function entryIdKey(key: string): string {
  return String(key ?? "")
    .replace(/\(.*?\)/g, " ")
    .replace(/\b(auto|autogenerated|generated|system)\b/gi, " ")
    .replace(/[^a-z0-9]/gi, "")
    .toLowerCase();
}

/** Columns that contain an "id"/"no" but are never the enquiry id. */
const NEVER_ID_KEYS = new Set([
  "emailid", "email", "mobile", "mobileno", "mobilenumber", "phone", "phoneno",
  "gstno", "gstin", "pono", "ponumber", "poqno", "qno", "challanno",
  "challannumber", "gatepassno", "gatpassno", "lrno", "invoiceno",
  "invoicenumber", "serialno", "serialnumber", "sno", "srno", "month",
  "office", "location", "timestamp", "salesclosedate", "entryref",
]);

/** ENQU-00048 / ENQ-00001 / ENQP-00003 / SES/26/0187 */
export function isIdShaped(value: string): boolean {
  return /^[A-Za-z]{1,8}[-/]?\d[A-Za-z0-9/.-]*$/.test(value);
}

/**
 * Reads one sheet cell as clean text.
 *
 * Cells pasted from Excel often carry zero-width spaces, non-breaking spaces or
 * soft hyphens. Those are invisible, so such a cell looks empty and the stored
 * id would be lost.
 */
function readCell(raw: unknown): string {
  if (raw === null || raw === undefined) return "";
  if (typeof raw === "object") return "";
  return String(raw)
    .replace(/[\u200B-\u200D\uFEFF\u00AD]/g, "")
    .replace(/\u00A0/g, " ")
    .trim();
}

/**
 * A cell that holds only digits is a serial number, an amount or a year — never
 * an enquiry id. Reading it would print "21" where "ENQU-00021" belongs, so it
 * is rejected and the row is reported as having no usable id.
 */
function isUsableId(value: string): boolean {
  if (!value) return false;
  if (!/[A-Za-z]/.test(value)) return false;
  return true;
}

/**
 * The row's Entry_ID exactly as the sheet holds it.
 * '' when that cell is genuinely empty — render nothing, never a placeholder.
 */
export function getEnquiryId(entry: Record<string, unknown>): string {
  if (!entry) return "";
  const keys = Object.keys(entry);

  // 1. the exact column
  for (const key of keys) {
    if (entryIdKey(key) !== "entryid") continue;
    const value = readCell(entry[key]);
    if (isUsableId(value)) return value;
  }

  // 2. a header that differs only by spelling
  for (const key of keys) {
    const k = entryIdKey(key);
    if (k === "entryid" || NEVER_ID_KEYS.has(k)) continue;
    if (!/^(entry|enquiry|inquiry|enq)?(id|no|number|code|ref|reference)(id|no|number|code|ref)?$/.test(k)) continue;
    const value = readCell(entry[key]);
    if (isUsableId(value)) return value;
  }

  // 3. unknown header naming: trust the value shape, never a PO/serial cell
  for (const key of keys) {
    if (NEVER_ID_KEYS.has(entryIdKey(key))) continue;
    const value = readCell(entry[key]);
    if (value && isIdShaped(value)) return value;
  }

  // 4. genuinely empty — never fabricate one
  return "";
}

/** True when the sheet itself holds an Entry_ID for this row. */
export function hasEnquiryId(entry: Record<string, unknown>): boolean {
  return getEnquiryId(entry) !== "";
}

/**
 * INTERNAL navigation key only — never rendered.
 *
 * The task detail view is handed the row object directly, so this exists only to
 * give React list keys a stable unique value for rows without an Entry_ID.
 */
export function getEntryRef(entry: Record<string, unknown>, rowIndex = 0): string {
  const id = getEnquiryId(entry);
  if (id) return id;

  const serial = readCell(entry?.Serial_No);
  if (serial && serial !== "0") return `SERIAL:${serial}`;

  return `ROW:${rowIndex}`;
}
